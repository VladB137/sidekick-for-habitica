/*
 * What the talking character says when tapped (Vlad, 2026-10-17): funny, witty, whimsical, nonsensical and
 * informational lines, all bundled; nothing is fetched or made up online. src/app/sayings.ts picks one.
 *
 * Each group is [when it fits, ...lines]. In a line:
 *   {name}     the speaker's name (its Stable name, Habitica's name for it, or the player's for the avatar)
 *   {species}  Habitica's name for its animal ("Tiger Cub", or "Tiger" for the mount)
 *   {potion}   Habitica's name for its hatching potion · {food} the food it likes (drop-potion pets only)
 *   {cls}      the player's class in Habitica's words (Warrior, Mage, Healer, Rogue) · {lvl} their level
 *   |          a beat: the typing waits there a moment (it is not shown)
 *   {perfect} {streakAch} {streakDays} {bestStreak} {toStreakAch} {basicPets} {basicLeft} {basicMounts} {petCount}
 *   {mountCount} {checkins} {questsWon} {daysIn} {rebirths} {gold} {xpToNext} {nextLvl} {growth} {mealsLeft}
 *   {checkinsLeft}
 *              the player's own numbers from the last read (src/app/sayings.ts accountWords); a count fills in only
 *              from 2 up, so a line never says “1 Perfect Days”.
 *   {checkinReward}  the next Check-In Reward in Habitica's words (src/app/checkins.ts) · {checkinRewardNext} the same,
 *              only when it is one check-in away
 * A line whose words can't be filled for this speaker is never picked.
 *
 * Rules: Relaxed never hears about crits (every line that mentions one is marked crit: true, and the test checks
 * it). Facts (kind 'info') hold against Habitica's code at the tag in src/engine/rules.ts, in Habitica's own words
 * for game terms; `src` names where, and tests/sayings.test.ts replays the numbers through Habitica's code. Nothing
 * here says the app is Habitica's, made or endorsed by it. Lines are at most 140 characters filled in.
 */
import type { Feast } from '../playground/scenes/feasts';

export type SayingKind = 'funny' | 'witty' | 'whimsical' | 'nonsense' | 'info';
export type SpeakerKind = 'avatar' | 'pet' | 'mount';
export type ClassKey = 'warrior' | 'wizard' | 'healer' | 'rogue';

/** When a line fits. Every field set must hold. */
export interface Fit {
  kind: SayingKind
  /** who may say it; any speaker when left out */
  who?: readonly SpeakerKind[]
  /** Habitica species (egg) keys */
  species?: readonly string[]
  /** Habitica hatching potion keys */
  potions?: readonly string[]
  /** the speaker's potion is a drop potion, a Magic Hatching Potion, or one of the wacky (April Fools) ones */
  potionKind?: 'drop' | 'premium' | 'wacky'
  /** a pet Habitica lets you feed (not a special pet, not wacky) */
  feeds?: boolean
  /** a special pet or mount (Veteran, Cerberus, Phoenix…): Habitica gives them, no egg hatches them */
  special?: boolean
  /** local hours [from, to); wraps past midnight when from > to */
  hours?: readonly [number, number]
  feast?: Feast
  conn?: 'live' | 'checking' | 'offline'
  /** Full only, and only while the next task crits */
  critNow?: boolean
  /** mentions crits: Full only */
  crit?: boolean
  /** only while damage is paused (resting in the Inn) */
  resting?: boolean
  cls?: readonly ClassKey[]
  minLvl?: number
  /** where in Habitica's code (website/common/script/… or website/server/… at the rules.ts tag) a fact holds */
  src?: string
}
