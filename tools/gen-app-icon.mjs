// Turns the app icon's pixels (tools/app-icon/icon.json) into the Android adaptive-icon layers and the web icons:
//   android/…/drawable/ic_launcher_background.xml, ic_launcher_foreground.xml, ic_launcher_monochrome.xml
//   public/icons/icon.svg (the middle 80 x 80, rounded), icon-192.png, icon-512.png, icon-maskable-512.png
// Every layer is vector: same-coloured pixels merged into rectangles, one path per colour, so the pixels stay square at
// any density. Rectangles reach EDGE past their pixels so neighbours overlap instead of leaving antialiased seams.
// The PNGs are Chromium's rendering of the same vectors (node tools/gen-app-icon.mjs; needs Playwright's Chromium).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { chromium } from 'playwright';

const icon = JSON.parse(readFileSync('tools/app-icon/icon.json', 'utf8'));
const N = icon.size, ALPHABET = '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz';
const EDGE = 0.05;
const grid = rows => rows.map(r => [...r].map(ch => ch === '.' ? -1 : ALPHABET.indexOf(ch)));
const bg = grid(icon.background), fg = grid(icon.foreground);
const both = bg.map((row, y) => row.map((c, x) => fg[y][x] >= 0 ? fg[y][x] : c));

// greedy rectangles per value: widest run first, then down while the rows below match
function rects(cells, x0, y0, w, h) {
  const seen = cells.map(r => r.map(() => false)), out = new Map();
  for (let y = y0; y < y0 + h; y++) for (let x = x0; x < x0 + w; x++) {
    const v = cells[y][x];
    if (v < 0 || seen[y][x]) continue;
    let rw = 1;
    while (x + rw < x0 + w && cells[y][x + rw] === v && !seen[y][x + rw]) rw++;
    let rh = 1;
    while (y + rh < y0 + h && [...Array(rw).keys()].every(i => cells[y + rh][x + i] === v && !seen[y + rh][x + i])) rh++;
    for (let j = 0; j < rh; j++) for (let i = 0; i < rw; i++) seen[y + j][x + i] = true;
    if (!out.has(v)) out.set(v, []);
    out.get(v).push([x - x0, y - y0, rw, rh]);
  }
  return out;
}
const num = n => String(+n.toFixed(2));
const pathData = list => list.map(([x, y, w, h]) =>
  `M${num(x - EDGE)} ${num(y - EDGE)}h${num(w + 2 * EDGE)}v${num(h + 2 * EDGE)}h${num(-w - 2 * EDGE)}z`).join('');
// colours drawn most-used first, so the small details land on top of the overlaps
const ordered = m => [...m.entries()].sort((a, b) => b[1].length - a[1].length);

const luma = hex => { const v = parseInt(hex.slice(1), 16); return (0.299 * (v >> 16) + 0.587 * (v >> 8 & 255) + 0.114 * (v & 255)) / 255; };
// Android 13+ themed icon: the foreground as one tinted shape. The alpha keeps the picture's light and shade
// (the system tints by alpha), with the dark outline faintest so the shapes stay apart.
const ALPHAS = [0.3, 0.55, 0.78, 1], STEPS = [0.17, 0.33, 0.55];
const mono = fg.map(row => row.map(c => c < 0 ? -1 : STEPS.filter(s => luma(icon.palette[c]) >= s).length));

const res = 'android/app/src/main/res/drawable';
const vector = (about, paths) => `<?xml version="1.0" encoding="utf-8"?>
<!-- ${about}, generated by tools/gen-app-icon.mjs from tools/app-icon/icon.json -->
<!-- long paths are fine here: the launcher and the splash draw each layer once, not on every frame -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:tools="http://schemas.android.com/tools" tools:ignore="VectorPath"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="${N}" android:viewportHeight="${N}">
${paths.join('\n')}
</vector>
`;
const colourPaths = cells => ordered(rects(cells, 0, 0, N, N)).map(([c, l]) =>
  `    <path android:fillColor="${icon.palette[c]}" android:pathData="${pathData(l)}"/>`);
writeFileSync(`${res}/ic_launcher_background.xml`, vector('App icon background layer: teal light rays', colourPaths(bg)));
writeFileSync(`${res}/ic_launcher_foreground.xml`, vector('App icon foreground layer: the owl on its crystal ball', colourPaths(fg)));
writeFileSync(`${res}/ic_launcher_monochrome.xml`, vector('App icon for Android 13+ themed icons: the foreground in one colour, its shading as alpha',
  ordered(rects(mono, 0, 0, N, N)).map(([a, l]) =>
    `    <path android:fillColor="#FFFFFFFF" android:fillAlpha="${ALPHAS[a]}" android:pathData="${pathData(l)}"/>`)));

// web: the 80 x 80 a launcher shows, as a rounded square; maskable: the full picture with the safe circle (33 dp)
// inside the 40 % radius maskable icons keep
const svg = (x0, w, rounded) => {
  const paths = ordered(rects(both, x0, x0, w, w)).map(([c, l]) => `<path fill="${icon.palette[c]}" d="${pathData(l)}"/>`).join('');
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${w}">${rounded
    ? `<clipPath id="r"><rect width="${w}" height="${w}" rx="${num(w * 112 / 512)}"/></clipPath><g clip-path="url(#r)">${paths}</g>` : paths}</svg>\n`;
};
const SHOWN = Math.round(N * 72 / 108), MASKABLE = 92;
writeFileSync('public/icons/icon.svg', svg((N - SHOWN) / 2, SHOWN, true));
const maskable = svg((N - MASKABLE) / 2, MASKABLE, false);

const browser = await chromium.launch(existsSync('/opt/pw-browsers/chromium') ? { executablePath: '/opt/pw-browsers/chromium' } : {});
const page = await browser.newPage();
for (const [src, out, size] of [[readFileSync('public/icons/icon.svg', 'utf8'), 'icon-192.png', 192],
  [readFileSync('public/icons/icon.svg', 'utf8'), 'icon-512.png', 512], [maskable, 'icon-maskable-512.png', 512]]) {
  await page.setViewportSize({ width: size, height: size });
  await page.setContent(`<html><body style="margin:0;background:transparent">${src.replace('<svg ', `<svg width="${size}" height="${size}" style="display:block" `)}</body></html>`);
  await page.screenshot({ path: `public/icons/${out}`, omitBackground: true, clip: { x: 0, y: 0, width: size, height: size } });
}
await browser.close();
console.log(`app icon: ${icon.palette.length} colours, Android layers + public/icons`);
