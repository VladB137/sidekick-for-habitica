// Run with Node 20 (Habitica's server runtime): records sin() bit patterns for the self-test.
// node tools/gen-sin-vectors.mjs > src/engine/sinVectors.ts
if (!process.versions.node.startsWith('20.')) console.error(`warning: running on Node ${process.versions.node}, not 20`);
const buf = new Float64Array(1); const u = new Uint32Array(buf.buffer);
const xs = [];
for (let s = 0; s < 64; s++) xs.push(s + 1);                       // small seeds
for (const s of [99, 314, 1000, 4096, 12345, 65535, 99999, 250000, 823549, 823550, 823551, 900000,
  1000000, 1647099, 1647100, 2500000, 10000000, 123456789, 2147483647, 1e12, 1.5e15, 9007199254740991]) xs.push(s + 1);
for (const s of [0.5, 17.25, 1234.75, 50000.125]) xs.push(s + 1);   // fractional seeds (unfloored gold)
let seed = 20260923;
const rnd = () => { seed = (seed * 1103515245 + 12345) >>> 0; return seed / 4294967296; };
for (let i = 0; i < 40; i++) xs.push(Math.floor(rnd() * 5e6) + 1);
for (let i = 0; i < 16; i++) xs.push(Math.floor(rnd() * 1e11) + 1);
const rows = xs.map(x => { buf[0] = Math.sin(x); return `  [${x}, 0x${u[1].toString(16)}, 0x${u[0].toString(16)}],`; });
console.log(`// Generated by tools/gen-sin-vectors.mjs on Node ${process.versions.node} (V8 ${process.versions.v8}).
// [x, high word, low word] of Math.sin(x) as Habitica's server computes it.
export const SIN_VECTORS: Array<[number, number, number]> = [
${rows.join('\n')}
];`);
