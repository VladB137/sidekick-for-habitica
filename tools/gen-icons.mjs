  'more_vert', 'info', 'warning', 'error', 'check_circle', 'logout', 'settings', 'open_in_new', 'refresh', 'visibility',
  'visibility_off', 'key', 'help_outline', 'emoji_events', 'casino', 'swap_horiz', 'fitness_center', 'favorite',
  'water_drop', 'auto_fix_high', 'monetization_on', 'grade', 'expand_more', 'expand_less', 'bolt', 'task_alt',
  'sports_martial_arts', 'savings', 'redeem', 'light_mode', 'dark_mode', 'brightness_auto', 'arrow_forward', 'done_all',
  'history', 'lock', 'code', 'wb_sunny', 'schedule', 'play_arrow', 'restart_alt',
